const PREFIX_PROPERTIES: &[&str] = &[
    "align-",
    "border-",
    "flex-",
    "font-",
    "grid-",
    "inset-",
    "justify-",
    "margin-",
    "outline-",
    "overflow",
    "padding-",
    "place-",
    "text-decoration-",
    "transition-",
];

#[must_use]
pub(crate) fn is_allowed_property(property: &str) -> bool {
    EXACT_PROPERTIES.contains(&property)
        || PREFIX_PROPERTIES
            .iter()
            .any(|prefix| property.starts_with(prefix))
}

