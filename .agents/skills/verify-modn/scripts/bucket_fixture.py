"""Build disposable bucket contract v2 fixtures for the Modn verifiers.

Every helper writes only below a caller-provided temporary directory. The
fixtures never read the repository's `buckets/main` submodule, and they sign a
catalog tree with a throwaway key generated by the repository example.
"""
import json
import shutil
import subprocess
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def write_bucket(root, name, title, packages=()):
    """Create a contract v2 bucket with the given package records.

    Each package is `(game_id, file_name, record)`. The file name already
    carries any `@<version>` suffix.
    """
    root.mkdir(parents=True, exist_ok=True)
    (root / "bucket.json").write_text(
        json.dumps({"schema_version": 2, "name": name, "title": title}),
        encoding="utf-8")
    for game, file_name, record in packages:
        folder = root / "mods" / game
        folder.mkdir(parents=True, exist_ok=True)
        (folder / file_name).write_text(json.dumps(record), encoding="utf-8")
    return root


def copy_modules(root, modules):
    """Copy one module directory per game into `games/<game-id>/`."""
    for game, source in modules.items():
        target = root / "games" / game
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(source, target)
    return root


def archive_pin(binary, archive, environment=None):
    """Return the CLI-reported BLAKE3 pin for one fixture archive."""
    completed = subprocess.run(
        [str(binary), "--json", "inspect", str(archive)],
        env=environment, capture_output=True, text=True, encoding="utf-8",
        errors="replace", timeout=60)
    require(completed.returncode == 0,
            f"inspect failed for {archive}: {completed.stderr}")
    pin = json.loads(completed.stdout)["blake3"]
    require(len(pin) == 64 and all(c in "0123456789abcdef" for c in pin),
            f"inspect returned an invalid BLAKE3 pin for {archive}: {pin!r}")
    return pin


def zip_tree(tree, target):
    """Store a bucket tree in a ZIP with root-relative POSIX entry names."""
    target.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_STORED) as output:
        for path in sorted(tree.rglob("*")):
            if path.is_file():
                output.write(path, path.relative_to(tree).as_posix())
    return target


def sign_tree(tree, signature, public_key):
    """Sign the catalog tree with an in-memory throwaway key.

    Returns the 16-hex-digit key identifier printed by the example.
    """
    completed = subprocess.run(
        ["cargo", "run", "--quiet", "--locked", "-p", "modn-core",
         "--example", "sign_catalog", "--",
         str(tree), str(signature), str(public_key)],
        cwd=REPO, capture_output=True, text=True, encoding="utf-8",
        errors="replace", timeout=600)
    require(completed.returncode == 0,
            f"sign_catalog failed: {completed.stderr}")
    key_id = completed.stdout.strip()
    require(len(key_id) == 16 and public_key.is_file(),
            f"sign_catalog returned no key identifier: {completed.stdout!r}")
    return key_id
